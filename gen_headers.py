"""Write ram.h and hw.h from ram.inc and hardware.inc. Run again when ram.inc changes."""
import re

out = ['// Game RAM at fixed addresses. Generated by gen_headers.py from ram.inc.',
       '#include <stdint.h>', '']
for name, addr, note in re.findall(r'^DEF (\w+) EQU \$(\w+)(?:\s*;\s*(.*))?$', open('ram.inc').read(), re.M):
    n = re.match(r'(\d+) bytes', note or '')
    if addr.lower().startswith('ff'):
        # SDCC 4.5.1 prints a bad address for `ldh (__at variable), a`. A cast address works.
        decl = f'#define {name} ' + (f'((uint8_t *)0x{addr})' if n else f'(*(uint8_t *)0x{addr})')
    else:
        decl = f'__at(0x{addr}) uint8_t {name}{f"[{n.group(1)}]" if n else ""};'
    out.append(decl + (f' // {note}' if note else ''))
open('ram.h', 'w').write('\n'.join(out) + '\n')

out = ['// Hardware registers. Generated by gen_headers.py from hardware.inc.',
       '#include <stdint.h>', '']
for name, addr in re.findall(r'^DEF (r\w+)\s+EQU\s+\$(ff[0-9a-f]{2})\b', open('hardware.inc').read(), re.M | re.I):
    out.append(f'volatile __at(0x{addr}) uint8_t {name};')
open('hw.h', 'w').write('\n'.join(out) + '\n')
